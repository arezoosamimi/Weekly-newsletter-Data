weekly_totals AS (
  SELECT
    dw.drop_name,
    dw.week_start,
    dw.week_end,
    SUM(o.gross_sales_usd - o.line_item_duties_usd - o.total_discounts_usd) AS total_digital_revenue,
    SUM(CASE WHEN o."style" ILIKE '%Accolade%'
             THEN o.gross_sales_usd - o.line_item_duties_usd - o.total_discounts_usd
             ELSE 0 END) AS weekly_accolade_revenue
  FROM drop_windows dw
  JOIN analytics_gold.gold_omni_order_line_item_detail o
    ON o.order_date BETWEEN dw.week_start AND dw.week_end
   AND o.digital_vs_retail = 'digital'
   AND COALESCE(o.is_lion_discount_applied, FALSE) = FALSE
   AND COALESCE(o.is_item_gwp_adj, FALSE) = FALSE
  GROUP BY 1, 2, 3
),

drop_revenue AS (
  SELECT
    dw.drop_name,
    dw.week_start,
    dw.week_end,
    SUM(o.gross_sales_usd - o.line_item_duties_usd - o.total_discounts_usd) AS drop_revenue,
    SUM(CASE WHEN o."style" ILIKE '%Accolade%'
             THEN o.gross_sales_usd - o.line_item_duties_usd - o.total_discounts_usd
             ELSE 0 END) AS drop_accolade_revenue,
    COUNT(DISTINCT CASE WHEN o."style" ILIKE '%Accolade%' THEN o."style" END) AS accolade_style_count,
    COUNT(DISTINCT o.product_title) AS distinct_product_titles
  FROM drop_windows dw
  JOIN product_drop_map pdm
    ON pdm.drop_name = dw.drop_name
  JOIN analytics_gold.gold_omni_order_line_item_detail o
    ON o.product_id = pdm.product_id
   AND o.order_date BETWEEN dw.week_start AND dw.week_end
   AND o.digital_vs_retail = 'digital'
   AND COALESCE(o.is_lion_discount_applied, FALSE) = FALSE
   AND COALESCE(o.is_item_gwp_adj, FALSE) = FALSE
  GROUP BY 1, 2, 3
)

SELECT
  wt.drop_name,
  wt.week_start,
  wt.week_end,
  wt.total_digital_revenue,
  dr.drop_revenue,
  ROUND(100.0 * dr.drop_revenue / NULLIF(wt.total_digital_revenue, 0), 2)          AS pct_of_window_digital_rev_from_drop,
  dr.drop_accolade_revenue,
  ROUND(100.0 * dr.drop_accolade_revenue / NULLIF(dr.drop_revenue, 0), 2)          AS pct_of_drop_rev_from_accolade,
  dr.accolade_style_count,
  wt.weekly_accolade_revenue,
  ROUND(100.0 * wt.weekly_accolade_revenue / NULLIF(wt.total_digital_revenue, 0), 2) AS pct_of_window_digital_rev_from_accolade,
  dr.distinct_product_titles,
  ROUND(dr.drop_revenue / NULLIF(dr.distinct_product_titles, 0), 2)                AS revenue_per_distinct_product_title
FROM weekly_totals wt
JOIN drop_revenue dr
  ON wt.drop_name = dr.drop_name
ORDER BY wt.week_start